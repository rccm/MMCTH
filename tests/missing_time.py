def has_missing_pixel_time(mm_path):
    """
    Return True if the variable 'pixel_time' in a MODMISR file contains any missing value.
    Missing values are those ≤ -1e9.
    """
    with Dataset(mm_path) as ds:
        arr = ds.variables['pixel_time'][:].astype(np.float64)
    arr[arr <= -1.0e9] = np.nan
    return np.isnan(arr).any()

