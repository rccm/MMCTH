c
c!OUTPUT PARAMETERS:
c    GET_GRID_INDEX    Return status
c                       0 => Success
c                      -1 => Latitude not in range -90 to 90
c                      -2 => Longitude not in range -180 to 180
c                      -3 => Grid index not in range 1 to 814880
c    GRID_INDEX        Index value in global grid (1-814880)
c
c!REVISION HISTORY:
c
